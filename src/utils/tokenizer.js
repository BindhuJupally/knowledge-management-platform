/**
 * Tokenize and normalize raw text
 * @param {string} text - Raw input string
 * @param {boolean} removeStopWords - Whether to filter out stop words (default: false for baseline fidelity, or true)
 * @returns {string[]} - Array of normalized tokens
 */
function tokenize(text, removeStopWords = false) {
  if (!text || typeof text !== 'string') {
    return [];
  }

  // 1. Lowercase
  // 2. Strip non-alphanumeric chars (keep spaces and alphanumeric characters)
  // 3. Split by whitespace
  const tokens = text
    .toLowerCase()
    .replace(/[^\w\s]/g, ' ')
    .split(/\s+/)
    .filter(token => token.length > 0);

  if (removeStopWords) {
    return tokens.filter(token => !STOP_WORDS.has(token));
  }

  return tokens;
}

module.exports = {
  tokenize,
  STOP_WORDS,
};
